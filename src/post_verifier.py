def verify_and_clean_comment(
    text: str,
    user_comment: Optional[str] = None,
    user_author: Optional[str] = None,
    primary_ticker: Optional[str] = None,
    generator_model: Optional[str] = None,
    run_ai_review: bool = True,
) -> Tuple[bool, str, Dict[str, Any]]:
    """
    Universal verification pipeline for ANY comment or reply.
    Combines Fast-Gate deterministic validation with Adversarial AI Review.

    Returns:
        (is_approved, clean_text, audit_summary)
    """
    cleaned = clean_etoro_formatting(text)
    if not cleaned:
        return False, "", {"decision": "REJECT", "issues": ["Commento vuoto"]}

    # Fast-gate: check rules
    is_clean, issues, cleaned_text = verify_post_deterministic(cleaned, primary_ticker=primary_ticker)

    # Comments have shorter character limit on eToro (max 1000)
    if len(cleaned_text) > 1000:
        issues.append(f"WARNING: Il commento eccede la lunghezza massima consentita da eToro ({len(cleaned_text)} > 1000).")

    audit_data = {}
    if run_ai_review and GENAI_AVAILABLE and os.environ.get("GEMINI_API_KEY"):
        audit_data = audit_comment_with_ai_reviewer(
            text=cleaned_text,
            user_comment=user_comment,
            user_author=user_author,
            primary_ticker=primary_ticker,
            generator_model=generator_model,
        )
        decision = audit_data.get("decision", "APPROVE")
        verified_text = audit_data.get("verified_text", cleaned_text)

        if decision == "REJECT":
            print(f"   ❌ COMMENT REJECTED BY REVIEWER: {audit_data.get('explanation')}")
            return False, "", audit_data

        if decision == "AUTO_CORRECT":
            print(f"   🛠️ COMMENT AUTO-CORRECTED BY REVIEWER: {audit_data.get('explanation')}")
            final_text = clean_etoro_formatting(verified_text)
            return True, final_text, audit_data

        return True, clean_etoro_formatting(verified_text), audit_data

    # Deterministic fallback
    if not is_clean:
        crit = [i for i in issues if i.startswith("CRITICAL")]
        if crit:
            print(f"   ❌ COMMENT BLOCKED by Deterministic Gate: {crit[0]}")
            return False, "", {"decision": "REJECT", "issues": issues}

    return True, cleaned_text, {"decision": "APPROVE", "issues": issues}


