def fix_sign_sentiment_oxymorons(text: str) -> str:
    """
    Guarantees mathematical and semantic coherence between direction words and signed percentages.
    Eliminates contradictions like 'chiuso in flessione del +2.26%' or 'balzo del -3.5%'.
    """
    if not text:
        return ""

    cleaned = text

    # Positive percentage (+X.XX% or +X%) associated with negative terminology
    cleaned = re.sub(
        r'\b(?:ha\s+)?chius(?:o|a|ero)\s+in\s+flessione\s+(?:del\s+)?(?=\+\d)',
        'ha chiuso in rialzo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:in\s+flessione|in\s+calo)\s+(?:del\s+)?(?=\+\d)',
        'in rialzo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:ha\s+)?(?:registrato|subito)\s+una\s+(?:flessione|correzione)\s+(?:del\s+)?(?=\+\d)',
        'ha registrato un rialzo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:cedendo|perdendo)\s+(?:il\s+)?(?=\+\d)',
        'guadagnando il ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:sceso|scesa|scesi|scese)\s+(?:del\s+)?(?=\+\d)',
        'salito del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\bin\s+territorio\s+negativo\s+(?:del\s+)?(?=\+\d)',
        'in territorio positivo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:ha\s+)?perso\s+(?:il\s+)?(?=\+\d)',
        'ha guadagnato il ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:mostrato\s+una\s+)?performance\s+negativa,?\s*(?:chiudendo\s+a\s+)?(?=\+\d)',
        'ha registrato una performance positiva, chiudendo a ',
        cleaned,
        flags=re.IGNORECASE,
    )
    # Fix 'Seduta in flessione per ... salito dell' / 'chiuso in flessione ... salito dell''
    cleaned = re.sub(
        r'\b(?:seduta|giornata)\s+in\s+(?:flessione|calo)\s+(per\b[^\n]{0,120}?\bsalit[oaie]\b)',
        r'Seduta positiva \1',
        cleaned,
        flags=re.IGNORECASE,
    )

    # Negative percentage (-X.XX% or -X%) associated with positive terminology
    cleaned = re.sub(
        r'\b(?:ha\s+)?chius(?:o|a|ero)\s+in\s+rialzo\s+(?:del\s+)?(?=-\d)',
        'ha chiuso in calo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:in\s+rialzo|in\s+guadagno)\s+(?:del\s+)?(?=-\d)',
        'in calo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:ha\s+)?(?:registrato|messo\s+a\s+segno)\s+un\s+(?:rialzo|balzo|rally)\s+(?:del\s+)?(?=-\d)',
        'ha registrato una flessione del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:guadagnando|avanzando)\s+(?:il\s+)?(?=-\d)',
        'cedendo il ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:salito|salita|saliti|salite|balzato|balzata)\s+(?:del\s+)?(?=-\d)',
        'sceso del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\bin\s+territorio\s+positivo\s+(?:del\s+)?(?=-\d)',
        'in territorio negativo del ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:ha\s+)?guadagnato\s+(?:il\s+)?(?=-\d)',
        'ha ceduto il ',
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(
        r'\b(?:mostrato\s+una\s+)?performance\s+positiva,?\s*(?:chiudendo\s+a\s+)?(?=-\d)',
        'ha registrato una performance negativa, chiudendo a ',
        cleaned,
        flags=re.IGNORECASE,
    )

    return cleaned


def enforce_benchmark_ground_truth(
    text: str,
    benchmark_daily: Optional[Dict[str, float]] = None,
    session_name: Optional[str] = None,
) -> Tuple[str, bool]:
    """
    Enforces strict mathematical ground truth and semantic direction for market benchmarks.
    Prevents and corrects hallucinations where positive benchmark closes (+X%) are reported
    as losses/negatives ('ha perso 0.66%', 'chiudendo a -1.21%', 'in flessione'),
    or where negative closes (-X%) are reported as gains ('in rialzo', 'guadagni').

    Returns:
        tuple: (corrected_text, is_modified)
    """
    if not text or not benchmark_daily:
        return text, False

    session_upper = (session_name or "").upper()
    is_close_session = (
        any(k in session_upper for k in ["CLOSE", "SERALE", "CHIUSURA", "FINE GIORNATA"]) or
        (not session_name and bool(re.search(r'\b(?:chiusura\s+usa|buonasera|fine\s+sessione|seduta\s+d\'oltreoceano)\b', text.lower())))
    )
    if not is_close_session:
        return text, False

    spx_perf = benchmark_daily.get('SPX500')
    ndx_perf = benchmark_daily.get('NSDQ100')
    if spx_perf is None and ndx_perf is None:
        return text, False

    cleaned = text
    orig = text

    is_market_positive = (
        (spx_perf is not None and spx_perf > 0.15) or
        (ndx_perf is not None and ndx_perf > 0.15)
    )
    is_market_negative = (
        (spx_perf is not None and spx_perf < -0.15) or
        (ndx_perf is not None and ndx_perf < -0.15)
    )

    if is_market_positive:
        # Case A: Market closed POSITIVE (e.g. SPX +0.67%, Nasdaq +1.21%)
        # 1. Correct explicit benchmark loss phrases & sign flips:
        if spx_perf is not None and spx_perf > 0:
            cleaned = re.sub(
                r'(\$?SPX500\b[^\n\.,;]{0,40}?\b(?:che\s+)?ha\s+perso\s+)(?:il\s+)?(?:\+|-)?\d+[\.,]?\d*%',
                f"$SPX500 che ha guadagnato +{spx_perf:.2f}%",
                cleaned,
                flags=re.IGNORECASE,
            )
            cleaned = re.sub(
                r'(\b(?:che\s+)?ha\s+perso\s+(?:il\s+)?(?:\+|-)?\d+[\.,]?\d*%\s+[^\n\.,;]{0,40}?\b\$?SPX500\b)',
                f"ha guadagnato +{spx_perf:.2f}% per l'indice $SPX500",
                cleaned,
                flags=re.IGNORECASE,
            )
            # Correct if SPX500 is mentioned followed by negative percentage like "-0.66%"
            cleaned = re.sub(
                r'(\$?SPX500\b[^\n\.,;]{0,30}?\b(?:chiuso\s+a|chiudendo\s+a|a)\s+)-(?:\d+[\.,]?\d*%)',
                rf"\1+{spx_perf:.2f}%",
                cleaned,
                flags=re.IGNORECASE,
            )

        if ndx_perf is not None and ndx_perf > 0:
            cleaned = re.sub(
                r'((?:il\s+)?(?:Nasdaq(?:\s*100)?|\$NSDQ100)\b[^\n\.,;]{0,50}?\b(?:ha\s+mostrato\s+una\s+)?performance\s+negativa,?\s*(?:chiudendo\s+a\s+)?)(?:\+|-)?\d+[\.,]?\d*%',
                f"il Nasdaq 100 ($NSDQ100) ha chiuso in rialzo a +{ndx_perf:.2f}%",
                cleaned,
                flags=re.IGNORECASE,
            )
            cleaned = re.sub(
                r'((?:il\s+)?(?:Nasdaq(?:\s*100)?|\$NSDQ100)\b[^\n\.,;]{0,40}?\b(?:che\s+)?ha\s+perso\s+)(?:il\s+)?(?:\+|-)?\d+[\.,]?\d*%',
                f"il Nasdaq 100 ($NSDQ100) che ha guadagnato +{ndx_perf:.2f}%",
                cleaned,
                flags=re.IGNORECASE,
            )
            # Correct if Nasdaq/NSDQ100 is followed by negative percentage like "-1.21%"
